const PIN_SVG = '<svg viewBox="0 0 24 24"><path d="M14 6l-4 5-3-3-4 6h18z"/></svg>';

let map = null;
let marker = null;

function initMap() {
  map = L.map("map", { scrollWheelZoom: false, zoomControl: true }).setView(PACKAGES.wayag.coords, 11);
  L.tileLayer("https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}", {
    attribution: "Citra © Esri, Maxar, Earthstar Geographics",
    maxZoom: 18
  }).addTo(map);
}

function setMarker(coords, label) {
  if (marker) {
    map.removeLayer(marker);
  }
  const icon = L.divIcon({
    className: "",
    html: '<div class="map-pin"><span class="pin-dot">' + PIN_SVG + '</span><span class="pin-label">' + label + '</span></div>',
    iconSize: [0, 0]
  });
  marker = L.marker(coords, { icon: icon }).addTo(map);
  map.setView(coords, 11);
}

function buildFacilities(list) {
  let html = "";
  list.forEach(function (f) {
    html += '<div class="facility-item">' +
      '<i data-lucide="' + f[0] + '"></i>' +
      '<span class="facility-text">' + f[1] + '</span>' +
      '</div>';
  });
  return html;
}

function render(id) {
  const p = PACKAGES[id] || PACKAGES.wayag;

  document.getElementById("headerImg").src = p.images[0];
  document.getElementById("headerImg").alt = p.title;
  document.getElementById("dTitle").textContent = p.title;
  document.getElementById("dRatingNum").textContent = p.rating;
  document.getElementById("dReviews").textContent = p.reviews;
  document.getElementById("dLocation").textContent = p.location;
  document.title = p.title + " - Jelajah Nusantara";

  document.getElementById("g1").src = p.images[1];
  document.getElementById("g2").src = p.images[2];
  document.getElementById("g3").src = p.images[3];
  document.getElementById("g4").src = p.images[4];

  document.getElementById("dDesc1").textContent = p.desc1;
  document.getElementById("dDesc2").textContent = p.desc2;

  const desc2El = document.getElementById("dDesc2");
  const readMoreEl = document.getElementById("readMore");
  desc2El.classList.add("desc-hidden");
  readMoreEl.textContent = "Baca selengkapnya.";
  readMoreEl.dataset.expanded = "false";

  document.getElementById("facilities").innerHTML = buildFacilities(p.facilities);

  setMarker(p.coords, p.mapLabel);
  lucide.createIcons();
}

document.getElementById("readMore").addEventListener("click", function (e) {
  e.preventDefault();
  const desc2El = document.getElementById("dDesc2");
  const isExpanded = this.dataset.expanded === "true";

  if (isExpanded) {
    desc2El.classList.add("desc-hidden");
    this.textContent = "Baca selengkapnya.";
    this.dataset.expanded = "false";
  } else {
    desc2El.classList.remove("desc-hidden");
    this.textContent = "Tutup.";
    this.dataset.expanded = "true";
  }
});

